#!/bin/sh
# Single-container supervisor.
#
# Clients keep using the real registry names (ghcr.io, quay.io, ...). DNS on the client side
# points those names at this container, and nginx picks the right cache by TLS server name:
#
#   CACHE_REGISTRIES --> one registry:2 pull-through process per line (127.0.0.1:5001, 5002, ...)
#                   --> one nginx server block per line, server_name = the upstream's hostname
#   plus the web UI (port 8080). Registries and UI run as the unprivileged "cache" user: it owns /data,
#   so the UI can delete cached files, but it cannot read the root-only CA key.
#
# If any process dies the container exits, so Docker's restart policy brings everything back.
set -eu
set -f   # never glob-expand hostnames

RUN_DIR="${RUN_DIR:-/run/registry}"
NGINX_CONF="${NGINX_CONF:-/etc/nginx/conf.d/registries.conf}"
DATA="${DATA_DIR:-/data}"
CERTS="${CERTS:-/certs}"
STATE_DIR="${STATE_DIR:-$DATA/.registry-cache}"
ACCESS_LOG="${ACCESS_LOG:-$STATE_DIR/access.log}"
CACHE_TTL="${CACHE_TTL:-720h}"
LOG_LEVEL="${LOG_LEVEL:-error}"
export CERTS STATE_DIR ACCESS_LOG

die() { echo "[entrypoint] ERROR: $*" >&2; exit 1; }
log() { echo "[entrypoint] $*"; }
trim() { printf '%s' "$1" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//'; }
yq()   { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"; }   # YAML single-quoted string

# CACHE_MAX_SIZE: empty or 0 means no limit; otherwise a size such as 50GB, 500MB, 1.5TB or 20GiB.
if ! printf '%s\n' "${CACHE_MAX_SIZE:-}" | grep -Eiq '^[[:space:]]*(([0-9]*\.?[0-9]+[[:space:]]*(([kmgtp]i?)?b?)?)?)[[:space:]]*$'; then
  die "CACHE_MAX_SIZE='${CACHE_MAX_SIZE}' is not a size. Use something like 50GB, 500MB or 1.5TB, or leave it empty for no limit."
fi
mkdir -p "$RUN_DIR" "$(dirname "$NGINX_CONF")" "$DATA"
rm -f "$RUN_DIR"/*.yml

# Which registries to cache: one line each, "id | display name | upstream URL". Set CACHE_REGISTRIES
# (docker-compose.yml does) to change the list; otherwise this built-in list is used.
DEFAULT_REGISTRIES='hub|Docker Hub|https://registry-1.docker.io
ghcr|GitHub Container Registry|https://ghcr.io
quay|Quay|https://quay.io
gcr|Google Container Registry|https://gcr.io
k8s|Kubernetes registry|https://registry.k8s.io
mcr|Microsoft Container Registry|https://mcr.microsoft.com'
printf '%s\n' "${CACHE_REGISTRIES:-$DEFAULT_REGISTRIES}" > "$RUN_DIR/registries.list"

cat > "$NGINX_CONF" <<CONF
# Generated by entrypoint.sh at start-up. Change CACHE_REGISTRIES instead.
ssl_certificate     /run/tls/server.crt;
ssl_certificate_key /run/tls/server.key;
ssl_protocols       TLSv1.2 TLSv1.3;
ssl_session_cache   shared:SSL:10m;
ssl_session_timeout 1h;
client_max_body_size 0;
chunked_transfer_encoding on;

CONF
# Registry requests as JSON lines for the UI: who pulled which manifest, and which blob fetches failed.
cat >> "$NGINX_CONF" <<'CONF'
log_format registry_json escape=json '{"t":$msec,"ip":"$remote_addr","h":"$host","m":"$request_method","u":"$request_uri","s":$status,"b":$body_bytes_sent,"rt":$request_time,"ua":"$http_user_agent"}';
map $request_uri $log_registry_request { default 0; ~^/v2/.+/(manifests|blobs)/ 1; }
CONF
echo "access_log ${ACCESS_LOG} registry_json if=\$log_registry_request;" >> "$NGINX_CONF"
echo >> "$NGINX_CONF"

# Only used to sign upload state, which a pull-through cache never resumes. Setting it silences the
# registry's "No HTTP secret provided" warning.
HTTP_SECRET="$(openssl rand -hex 32)"

ui_regs=""
started=""
hosts=""
n=0
while IFS='|' read -r raw_id raw_name raw_up _rest || [ -n "${raw_id:-}" ]; do
  id="$(trim "${raw_id:-}")"
  case "$id" in ''|'#'*) continue ;; esac
  case "$id" in *[!a-z0-9-]*|-*) die "invalid registry id '$id' (lowercase letters, digits and hyphens only)" ;; esac
  name="$(trim "${raw_name:-}")"; [ -n "$name" ] || name="$id"
  upstream="$(trim "${raw_up:-}")"
  [ -n "$upstream" ] || die "registry '$id' has no upstream URL in CACHE_REGISTRIES"
  case "$upstream" in http://*|https://*) ;; *) upstream="https://$upstream" ;; esac

  # The upstream's hostname is what clients type, so it is also what nginx routes on.
  host="${upstream#*://}"; host="${host%%/*}"
  case "$host" in
    *:*) die "registry '$id': '$host' has a port. Clients reach the cache on 443, so the name must not include one." ;;
    ''|*[!a-z0-9.-]*) die "registry '$id': '$host' is not a lowercase hostname" ;;
  esac
  case " $hosts " in *" $host "*) die "hostname '$host' appears twice in CACHE_REGISTRIES" ;; esac
  hosts="$hosts $host"

  n=$((n + 1))
  port=$((5000 + n))

  # Optional upstream credentials: HUB_USERNAME / HUB_PASSWORD, GHCR_USERNAME, ...
  up="$(printf '%s' "$id" | tr 'a-z-' 'A-Z_')"
  eval "user=\${${up}_USERNAME:-}"
  eval "pass=\${${up}_PASSWORD:-}"
  if [ -n "$user" ] && [ -z "$pass" ]; then die "${up}_USERNAME is set but ${up}_PASSWORD is empty"; fi
  if [ -z "$user" ] && [ -n "$pass" ]; then die "${up}_PASSWORD is set but ${up}_USERNAME is empty"; fi
  if [ -z "$user" ] && [ "$host" = "registry-1.docker.io" ]; then
    log "note: Docker Hub is anonymous. Set HUB_USERNAME and HUB_PASSWORD to avoid its pull rate limit."
  fi

  {
    cat <<YML
version: 0.1
log:
  level: ${LOG_LEVEL}
storage:
  filesystem:
    rootdirectory: ${DATA}/${id}
  delete:
    enabled: true
http:
  addr: 127.0.0.1:${port}
  secret: ${HTTP_SECRET}
proxy:
  remoteurl: $(yq "$upstream")
  ttl: ${CACHE_TTL}
YML
    if [ -n "$user" ]; then
      echo "  username: $(yq "$user")"
      echo "  password: $(yq "$pass")"
    fi
  } > "$RUN_DIR/$id.yml"

  cat >> "$NGINX_CONF" <<CONF
server {
    listen 443 ssl;
    server_name ${host};

    # Lets the container detect a DNS loop (this name resolving back to the cache itself).
    location = /.well-known/registry-cache-probe { return 200 "registry-cache\n"; }

    location / {
        proxy_pass http://127.0.0.1:${port};
        include /etc/nginx/proxy-common.conf;
    }
}

CONF
  ui_regs="${ui_regs}${id}|${name}|${host}
"
  started="$started $id"
  log "registry '$id': ${host} -> ${upstream}$([ -n "$user" ] && echo ' (authenticated)')"
done < "$RUN_DIR/registries.list"

[ "$n" -gt 0 ] || die "no registries defined in CACHE_REGISTRIES"

# Any other hostname (including the bare IP) gets the web UI.
cat >> "$NGINX_CONF" <<CONF
server {
    listen 443 ssl default_server;
    server_name _;
    location / {
        proxy_pass http://127.0.0.1:8080;
        proxy_set_header Host \$http_host;
        proxy_read_timeout 180s;
    }
}
CONF

if [ "${GENERATE_ONLY:-0}" = "1" ]; then exit 0; fi

# ---- Data ownership --------------------------------------------------------------
# Registries and the UI run as the unprivileged "cache" user. Sharing one user lets the UI delete cached
# files, while the root-only CA key stays unreadable to both. A fresh bind mount is owned by root, so
# claim it once; after that the check is a single stat.
if [ "$(stat -c %U "$DATA")" != "cache" ]; then
  log "giving the cache user ownership of $DATA (first start, or data from an older version)..."
  chown -R cache:cache "$DATA" 2>/dev/null || log "WARNING: could not chown $DATA; deleting from the UI may fail"
fi
mkdir -p "$STATE_DIR"
touch "$ACCESS_LOG"
chown cache:cache "$STATE_DIR" "$ACCESS_LOG" 2>/dev/null || true
chmod 644 "$ACCESS_LOG" 2>/dev/null || true

# ---- TLS ---------------------------------------------------------------------
# Use the certificate you provide, or generate one that covers every registry name.
TLS_HOSTS="${hosts# }" sh /usr/local/bin/tls.sh
for h in $hosts; do
  if ! openssl x509 -in /run/tls/server.crt -noout -checkhost "$h" 2>/dev/null | grep -q 'does match'; then
    log "WARNING: the server certificate does not cover $h. Clients will reject TLS for it."
  fi
done
nginx -t >/dev/null 2>&1 || { nginx -t; die "generated nginx configuration is invalid"; }

# ---- Environment for children --------------------------------------------------
# Extra roots for upstream TLS (Go merges every PEM in these directories).
export SSL_CERT_DIR="/upstream-ca:/etc/ssl/certs"
export REGISTRIES="$ui_regs" DATA_DIR="$DATA" PUBLIC_CERT_DIR="${PUBLIC_DIR:-/run/public-certs}"
[ -z "${HTTPS_PROXY:-}${HTTP_PROXY:-}" ] || log "upstream traffic goes through proxy ${HTTPS_PROXY:-$HTTP_PROXY}"

# ---- Supervise -----------------------------------------------------------------
pids=""
start() { "$@" & pids="$pids $!"; }
alive() { [ -r "/proc/$1/status" ] && ! grep -q '^State:[[:space:]]*Z' "/proc/$1/status"; }
stop()  { kill $pids ${probe_pid:-} 2>/dev/null || true; wait 2>/dev/null || true; exit "${1:-0}"; }
trap 'stop 0' TERM INT

for id in $started; do start su-exec cache registry serve "$RUN_DIR/$id.yml"; done
start nginx -g 'daemon off;'
start su-exec cache python3 /app/app.py
log "up: $n registries on :443 ($(echo $hosts)), UI on :8080"

# A cache whose upstream names resolve back to itself would loop. Check once, shortly after start.
(
  sleep 5
  for h in $hosts; do
    reply="$(wget -q -T 5 --no-check-certificate -O - "https://$h/.well-known/registry-cache-probe" 2>/dev/null || true)"
    case "$reply" in
      *registry-cache*) echo "[entrypoint] WARNING: inside this container $h resolves to the cache itself, so pulls will loop." \
                             "Set UPSTREAM_DNS to a resolver that returns the real address." >&2 ;;
    esac
  done
) &
probe_pid=$!

while :; do
  for p in $pids; do
    alive "$p" || { echo "[entrypoint] process $p exited; stopping container" >&2; stop 1; }
  done
  sleep 2 &
  wait $!
done
